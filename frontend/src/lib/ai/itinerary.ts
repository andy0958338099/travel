/** 取得當天行程, dayNumber 0-9 */
export function getItineraryForDay(dayNumber: number): string[] {
  return ITINERARY[String(dayNumber)] ?? [];
}

/** 格式化 itinerary 成 LLM prompt 區段 (沒行程就不加) */
export function formatItineraryForLLM(dayNumber: number): string {
  const items = getItineraryForDay(dayNumber);
  if (items.length === 0) return "";
  return [
    `【當天行程 — 聖上 8-10 提供的真實時段表】`,
    `Day ${dayNumber} (${dayNumber === 0 ? "前言" : dayNumber === 9 ? "後記" : "第 N 天"}) 共 ${items.length} 個時段:`,
    ...items.map((it, idx) => `  ${idx + 1}. ${it}`),
    "",
    `重要: 聖上原文提到的時段/地點/動作, 應對應到行程表的時段 — 行程表是「事實基準」, 不是規劃。`,
    `✅ 潤飾時可用行程表當時間軸錨點 (例: 「下午 02:15 在豫園, 行程表寫 12:00~15:30」)`,
    `❌ 禁止: 行程表沒寫的時段/地點不可虛構, 行程表寫 15:00 在嘉廷飯店, 不可寫 14:00 在南京東路。`,
  ].join("\n");
}

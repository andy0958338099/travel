/**
 * 給 polish-d1 prompt 用, 取前 N 天 (節省 token)
 *   day = 1..8
 */
export function getItineraryForDay(day: number): string {
  if (day < 1 || day > 8) return "";
  const lines = JIANGNAN_ITINERARY.split("\n");
  const result: string[] = [];
  let capture = false;
  for (const line of lines) {
    if (line.includes(`=== 07/${day.toString().padStart(2, "0")}`)) {
      capture = true;
    } else if (capture && line.startsWith("=== ")) {
      break;
    }
    if (capture) result.push(line);
  }
  return result.join("\n");
}